#!/usr/bin/env python3
"""Generate main/tune_data.h from the RTTTL files in tunes/.

Mirrors tools/gen_font.py, which produces main/font_oled.h: the tuned assets
live in a generated header so the firmware never has to read a filesystem it
does not have. Tunes are plain text in flash, which is the whole point of
choosing RTTTL - the alternative is a baked PCM array, and esp-idf-a2dp-source
carries 5.3 MB of that (about thirteen seconds of 44.1 kHz stereo) in a project
with a 1.875 MB partition.

Usage:
    python tools/gen_tunes.py            regenerate main/tune_data.h from tunes/
    python tools/gen_tunes.py --list     show what is in there

Adding a tune is: drop a .rtttl file in tunes/ and run this. Names come from
the file name, not from the RTTTL name field, so the on-screen list is stable
and the strings can carry the long names and stray spaces that real RTTTL has.
"""
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
TUNE_DIR = os.path.join(ROOT, "tunes")
OUT = os.path.join(ROOT, "main", "tune_data.h")

MAX_NAME = 14
MAX_TUNE = 2048     # RTTTL strings run long. This was 400, which silently
                    # truncated a full-length melody (RickRoll is ~1.3 KB)
                    # into a tune that just stopped halfway with no warning.
                    # A cap that corrupts data is worse than no cap.


def c_escape(s):
    return s.replace("\\", "\\\\").replace('"', '\\"')


def load():
    if not os.path.isdir(TUNE_DIR):
        return []
    tunes = []
    for fn in sorted(os.listdir(TUNE_DIR)):
        if not fn.lower().endswith(".rtttl"):
            continue
        path = os.path.join(TUNE_DIR, fn)
        with open(path, "r", encoding="utf-8", errors="replace") as f:
            raw = f.read()
        # Strip a UTF-8 BOM. Windows editors add one silently, and it makes
        # the comment check below miss, which turns every file into a
        # misleading "not an RTTTL line" message for its own header.
        raw = raw.lstrip("\ufeff")
        # One RTTTL per line; ignore blanks and comments so a tune file can
        # carry provenance above the string.
        for line in raw.splitlines():
            line = line.strip()
            if not line or line.startswith("#") or line.startswith("//"):
                continue
            if line.count(":") < 2:
                print("  skip %s: not an RTTTL line" % fn)
                continue
            name = os.path.splitext(fn)[0]
            name = re.sub(r"[^A-Za-z0-9 _-]", "", name).strip()[:MAX_NAME]
            if len(line) > MAX_TUNE:
                line = line[:MAX_TUNE]
            tunes.append((name, line))
            break
    return tunes


def main():
    tunes = load()
    if "--list" in sys.argv:
        print("%d tune(s) in %s" % (len(tunes), TUNE_DIR))
        for n, t in tunes:
            print("  %-16s %3d bytes" % (n, len(t)))
        return 0
    if not tunes:
        print("no tunes found in %s" % TUNE_DIR)
        return 1

    w = []
    w.append("/* Generated by tools/gen_tunes.py - do not edit.")
    w.append(" * Source: the tunes directory. Regenerate after adding a tune.")
    w.append(" *")
    w.append(" * const, so these live in flash and cost no RAM. That is the reason")
    w.append(" * for RTTTL over any binary format: a whole tune is a couple of")
    w.append(" * hundred bytes of text here, where the same melody as baked PCM")
    w.append(" * would be hundreds of kilobytes.")
    w.append(" */")
    w.append("#pragma once")
    w.append("")
    w.append("#define TUNE_COUNT %d" % len(tunes))
    w.append("")
    w.append("typedef struct {")
    w.append("    const char *name;")
    w.append("    const char *rtttl;")
    w.append("} tune_entry_t;")
    w.append("")
    w.append("static const tune_entry_t k_tunes[TUNE_COUNT] = {")
    for n, t in tunes:
        w.append('    {"%s",' % c_escape(n))
        w.append('     "%s"},' % c_escape(t))
    w.append("};")
    w.append("")

    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(w))
    print("wrote %s: %d tunes, %d bytes"
          % (os.path.relpath(OUT, ROOT), len(tunes), os.path.getsize(OUT)))
    return 0


if __name__ == "__main__":
    sys.exit(main())